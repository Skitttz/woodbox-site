const browserLanguage = navigator.languages?.[0] || navigator.language || "en";
let currentLang = /^pt(?:-|$)/i.test(browserLanguage) ? "pt-BR" : "en";

try {
  // The old key also stored automatic defaults, not just explicit choices.
  const savedLang = localStorage.getItem("woodbox-language-preference");
  if (translations[savedLang]) currentLang = savedLang;
} catch {
  // The page remains usable when browser storage is unavailable.
}

function getText(key) {
  return translations[currentLang]?.[key] || translations.en[key] || key;
}

function applyLanguage(lang, remember = false) {
  currentLang = translations[lang] ? lang : "en";
  if (remember) {
    try {
      localStorage.setItem("woodbox-language-preference", currentLang);
    } catch {
      // Language changes still work without persistence.
    }
  }
  document.documentElement.lang = currentLang;
  document.title = currentLang === "pt-BR"
    ? "Woodbox — Gerenciador desktop open source para bancos"
    : "Woodbox — Open-source desktop database manager";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = getText(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":").map((value) => value.trim());
      if (attribute && key) element.setAttribute(attribute, getText(key));
    });
  });

  document.querySelectorAll(".lang-option").forEach((button) => {
    const active = button.dataset.lang === currentLang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  updateGalleryAlt();
  updateDownloadButtons();
}

function updateGalleryAlt() {
  const image = document.querySelector("#galleryImage");
  const activeButton = document.querySelector(".gallery-button.is-active");
  if (!image || !activeButton) return;

  const screen = galleryScreens[Number(activeButton.dataset.screen)];
  image.alt = screen.alt[currentLang];
  document.querySelector("#galleryCaption").textContent = image.alt;
  document.querySelector("#galleryFullImage").href = screen.src;
}

function setupLanguageSwitch() {
  document.querySelectorAll(".lang-option").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang, true));
  });
}

const releasesUrl = "https://github.com/antonycms/woodbox/releases/latest";
let selectedDownload = null;

async function detectDownloadPlatform() {
  const ua = navigator.userAgent || "";
  const platform = navigator.userAgentData?.platform || navigator.platform || "";
  if (/Android|iPhone|iPad|iPod/i.test(ua) || navigator.userAgentData?.mobile ||
      (/Mac/i.test(platform) && navigator.maxTouchPoints > 1)) return null;

  const os = /Win/i.test(platform) ? "windows"
    : /Mac/i.test(platform) ? "mac"
    : /Linux/i.test(platform) && !/CrOS/i.test(ua) ? "linux" : null;
  if (!os) return null;

  let arch = /aarch64|arm64/i.test(ua) ? "arm64"
    : /x86_64|amd64|Win64|WOW64|x64/i.test(ua) ? "x64" : null;
  try {
    const hints = await navigator.userAgentData?.getHighEntropyValues(["architecture", "bitness"]);
    if (hints?.architecture === "arm" && hints.bitness === "64") arch = "arm64";
    if (hints?.architecture === "x86") arch = hints.bitness === "64" ? "x64" : "ia32";
  } catch {
    // Some browsers do not expose architecture hints.
  }
  return { os, arch };
}

function selectReleaseAsset(assets, platform) {
  if (!platform) return null;
  const extensions = { windows: /\.exe$/i, mac: /\.dmg$/i, linux: /\.AppImage$/i };
  const candidates = assets.filter((asset) =>
    typeof asset.name === "string" && extensions[platform.os]?.test(asset.name) &&
    asset.browser_download_url?.startsWith("https://github.com/antonycms/woodbox/releases/download/")
  );
  return candidates.find((asset) => {
    const name = asset.name.toLowerCase();
    if (platform.os === "mac" && /(?:^|[-_.])universal(?:[-_.]|$)/.test(name)) return true;
    if (!platform.arch) return false;
    const arch = /(?:^|[-_.])(?:arm64|aarch64)(?:[-_.]|$)/.test(name) ? "arm64"
      : /(?:^|[-_.])(?:x64|x86_64|amd64)(?:[-_.]|$)/.test(name) ? "x64"
      : /(?:^|[-_.])(?:ia32|i386|i686)(?:[-_.]|$)/.test(name) ? "ia32"
      // The current Windows and Linux pipelines publish unlabelled x64 installers.
      : platform.os !== "mac" ? "x64" : null;
    return arch === platform.arch;
  }) || null;
}

function updateDownloadButtons() {
  document.querySelectorAll("[data-download]").forEach((button) => {
    button.href = selectedDownload?.asset.browser_download_url || releasesUrl;
    const label = button.querySelector("[data-i18n]");
    label.textContent = getText(selectedDownload ? `download.${selectedDownload.os}` : label.dataset.i18n);
    if (selectedDownload) {
      button.removeAttribute("target");
      button.title = selectedDownload.asset.name;
    }
  });
}

async function loadLatestDownload() {
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 5000);
  try {
    const [platform, response] = await Promise.all([
      detectDownloadPlatform(),
      fetch("https://api.github.com/repos/antonycms/woodbox/releases/latest", {
        headers: { Accept: "application/vnd.github+json" },
        cache: "no-cache",
        signal: controller.signal
      })
    ]);
    if (!response.ok) return;
    const release = await response.json();
    if (release.draft || release.prerelease || !Array.isArray(release.assets)) return;
    const asset = selectReleaseAsset(release.assets, platform);
    if (asset) selectedDownload = { asset, os: platform.os };
  } catch {
    // Keep a working releases link when the API is offline or rate-limited.
  } finally {
    window.clearTimeout(timeout);
    updateDownloadButtons();
  }
}

function setupDownloads() {
  const ready = loadLatestDownload();
  document.querySelectorAll("[data-download]").forEach((button) => {
    button.addEventListener("click", async (event) => {
      if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
      event.preventDefault();
      button.setAttribute("aria-busy", "true");
      await ready;
      button.removeAttribute("aria-busy");
      window.location.assign(button.href);
    });
  });
}

function setupGallery() {
  const image = document.querySelector("#galleryImage");
  if (!image) return;

  document.querySelectorAll(".gallery-button").forEach((button) => {
    button.addEventListener("click", () => {
      const screen = galleryScreens[Number(button.dataset.screen)];
      document.querySelectorAll(".gallery-button").forEach((item) => {
        const active = item === button;
        item.classList.toggle("is-active", active);
        item.setAttribute("aria-pressed", String(active));
      });
      image.src = screen.src;
      updateGalleryAlt();
    });
  });
}

function setupReveal() {
  const elements = document.querySelectorAll(".reveal");

  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    elements.forEach((element) => element.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.14 });

  elements.forEach((element) => {
    element.classList.add("is-pending");
    observer.observe(element);
  });
}

